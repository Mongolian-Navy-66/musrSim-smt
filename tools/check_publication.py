#!/usr/bin/env python3
"""Check staged publication content, or a clean exported tree (standard library only)."""
import argparse
import ast
import fnmatch
import html
import json
import os
from pathlib import Path, PurePosixPath
import posixpath
import re
import subprocess
import sys
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
POLICY = 'manifests/publication_policy.json'
ASSETS = 'manifests/publication_assets.txt'
EXCEPTIONS = 'manifests/publication_link_exceptions.json'


def git(root, *args):
    return subprocess.check_output(['git', '--no-optional-locks', '-C', str(root), *args])


class Snapshot:
    def __init__(self, root, indexed):
        self.root = root
        self.indexed = indexed
        self.entries = {}
        self.cache = {}
        if indexed:
            records = git(root, 'ls-files', '--stage', '-z').decode('utf-8').split('\0')
            for record in filter(None, records):
                meta, name = record.split('\t', 1)
                mode, oid, stage = meta.split()
                if stage != '0' or mode not in ('100644', '100755'):
                    raise ValueError('Unmerged or unsupported index entry: ' + name)
                self.entries[name] = oid
            oids = list(dict.fromkeys(self.entries.values()))
            result = subprocess.check_output(
                ['git', '-C', str(root), 'cat-file', '--batch-check=%(objectname) %(objectsize)'],
                input=('\n'.join(oids) + '\n').encode())
            sizes = dict(line.split() for line in result.decode().splitlines())
            self.sizes = {name: int(sizes[oid]) for name, oid in self.entries.items()}
        else:
            for folder, dirs, files in os.walk(root):
                dirs[:] = [d for d in dirs if d != '.git']
                for filename in files:
                    path = Path(folder) / filename
                    if path.is_symlink():
                        raise ValueError('Symlink in export: ' + str(path))
                    self.entries[path.relative_to(root).as_posix()] = None
            self.sizes = {name: (root / name).stat().st_size for name in self.entries}

    def read(self, name):
        if name not in self.entries:
            raise ValueError('Not in publication snapshot: ' + name)
        if name not in self.cache:
            self.cache[name] = (git(self.root, 'cat-file', 'blob', self.entries[name])
                                if self.indexed else (self.root / name).read_bytes())
        return self.cache[name]

    def text(self, name):
        return self.read(name).decode('utf-8-sig')

    def present(self, name):
        return name in self.entries or any(x.startswith(name.rstrip('/') + '/') for x in self.entries)


def restricted(name, policy):
    parts = PurePosixPath(name).parts
    if name in policy.get('local_paths', []):
        return True
    if any(name.lower().endswith(ext) for ext in policy['asset_suffixes']):
        return True
    if any(name.startswith(prefix) for prefix in policy['protected_prefixes']):
        return True
    if any(fnmatch.fnmatchcase(part, pat) for part in parts[:-1]
           for pat in policy['local_directories']):
        return True
    if parts and parts[0] == 'simulation':
        if any(fnmatch.fnmatchcase(part, pat) for part in parts[2:-1]
               for pat in policy['simulation_generated_directories']):
            return True
    return any(fnmatch.fnmatchcase(parts[-1], pat) for pat in policy['local_filenames'])


def ignore_text(policy, assets):
    lines = ['# Generated by tools/check_publication.py --write-ignore.',
             '# Source files use ordinary Git tracking; artifacts require explicit approval.', '']
    lines += ['*' + ext for ext in policy['asset_suffixes']]
    lines += policy['local_filenames']
    lines += ['/' + name for name in policy.get('local_paths', [])]
    lines += ['**/' + name + '/**' for name in policy['local_directories']]
    lines += ['/' + prefix + '**' for prefix in policy['protected_prefixes']]
    lines += ['/simulation/**/' + name + '/**' for name in policy['simulation_generated_directories']]
    lines += ['!.env.example', '!.env.sample', '', '# Exact artifact and special-input exceptions.']
    parents = set()
    for name in assets:
        parents.update(str(p) for p in PurePosixPath(name).parents if str(p) != '.')
    lines += ['!/' + p + '/' for p in sorted(parents, key=lambda p: (p.count('/'), p))]
    lines += ['!/' + p for p in sorted(assets)]
    return '\n'.join(lines) + '\n'


def markdown_targets(text):
    # Code examples are not rendered document dependencies.
    text = re.sub(r'^\s*(```|~~~)[\s\S]*?^\s*\1[^\n]*$', '', text, flags=re.M)
    for match in re.finditer(r'!?\[[^\]\n]*\]\(\s*(<[^>\n]+>|[^)\n]+)\)', text):
        target = match.group(1).strip()
        if target.startswith('<'):
            target = target[1:-1]
        else:
            target = re.sub(r'\s+["\'][^"\']*["\']\s*$', '', target)
        yield html.unescape(target)
    # Reference definitions are dependencies too, including image references.
    for match in re.finditer(r'^\s{0,3}\[[^\]\n]+\]:\s*(<[^>\n]+>|\S+)', text, re.M):
        yield html.unescape(match.group(1).strip('<>'))


def dependencies(tree):
    issues = {}
    checked = 0

    def visit(document, target, search=None, suffixes=('',)):
        nonlocal checked
        if not target or target.startswith('#'):
            return
        if re.match(r'^(https?|mailto|ftp|data|doi):', target, re.I):
            return
        kind = None
        if '{{' in target or re.search(r'#[1-9]', target):
            kind = 'template'
        elif target.startswith(('/', '\\')) or re.match(r'^[A-Za-z][\w+.-]*:', target):
            kind = 'external'
        else:
            path = unquote(target.split('#', 1)[0].split('?', 1)[0]).replace('\\', '/')
            folders = search or [posixpath.dirname(document)]
            resolved = [posixpath.normpath(posixpath.join(folder, path)) for folder in folders]
            if any(tree.present(p + ext) for p in resolved for ext in suffixes):
                checked += 1
                return
            kind = 'external' if any(p == '..' or p.startswith('../') for p in resolved) else 'missing'
        issues[(document, target)] = {'document': document, 'target': target, 'kind': kind}

    for name in sorted(tree.entries):
        suffix = PurePosixPath(name).suffix.lower()
        if suffix not in ('.md', '.tex'):
            continue
        text = tree.text(name)
        if suffix == '.md':
            for target in markdown_targets(text):
                visit(name, target)
        else:
            folders = [posixpath.dirname(name)]
            for line in text.splitlines():
                if line.lstrip().startswith('\\graphicspath'):
                    folders += [posixpath.normpath(posixpath.join(posixpath.dirname(name), x))
                                for x in re.findall(r'\{([^{}]+)\}', line)]
            for target in re.findall(r'\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}', text):
                visit(name, target, folders, ('', '.pdf', '.png', '.jpg', '.jpeg', '.eps', '.svg'))
            for target in re.findall(r'\\(?:input|include)\{([^}]+)\}', text):
                visit(name, target, suffixes=('', '.tex'))
    return checked, list(issues.values())


def validate(tree):
    policy = json.loads(tree.text(POLICY))
    if policy['schema_version'] != 1:
        raise ValueError('Unsupported publication policy schema')
    listed = [line for line in tree.text(ASSETS).splitlines() if line and not line.startswith('#')]
    assets = set(listed)
    if len(assets) != len(listed):
        raise ValueError('Duplicate artifact paths')
    errors = []
    for name in assets:
        if name not in tree.entries:
            errors.append('Allowlisted artifact absent from snapshot: ' + name)
    for name in sorted(tree.entries):
        parts = PurePosixPath(name).parts
        if name.startswith('/') or '..' in parts or '\\' in name:
            errors.append('Invalid path: ' + name)
        if tree.sizes[name] > policy['max_file_bytes']:
            errors.append('File exceeds size limit: ' + name)
        if restricted(name, policy) and name not in assets and name not in ('.env.example', '.env.sample'):
            errors.append('Artifact/local file not allowlisted: ' + name)
        if name.endswith('.py'):
            ast.parse(tree.text(name), filename=name)
    if tree.text('.gitignore').replace('\r\n', '\n') != ignore_text(policy, assets):
        errors.append('Ignore rules differ from policy; run --write-ignore and stage the result')
    checked, issues = dependencies(tree)
    exceptions = json.loads(tree.text(EXCEPTIONS))
    expected = {(x['document'], x['target'], x['kind']) for x in exceptions}
    actual = {(x['document'], x['target'], x['kind']) for x in issues}
    if len(expected) != len(exceptions):
        errors.append('Duplicate dependency exceptions')
    for document, target, kind in sorted(actual - expected):
        errors.append('Unapproved {} dependency: {} -> {}'.format(kind, document, target))
    for document, target, kind in sorted(expected - actual):
        errors.append('Stale {} exception: {} -> {}'.format(kind, document, target))
    sample_name = 'manifests/example_sample.json'
    if sample_name in tree.entries:
        sample = json.loads(tree.text(sample_name))
        original = json.loads(tree.text(sample['provenance_manifest']))
        for key in ('root', 'macro'):
            name = sample[key]
            if name not in tree.entries:
                errors.append('Missing sample: ' + name)
            if sample['sha256'][name] != original[key + '_sha256']:
                errors.append('Inconsistent recorded sample provenance: ' + name)
        # The explicitly published pilot is small; never open production ROOT files.
        import hashlib
        for name, expected_hash in sample['sha256'].items():
            if name not in tree.entries or tree.sizes[name] >= 1_000_000:
                errors.append('Missing or oversized pilot component: ' + name)
            elif hashlib.sha256(tree.read(name)).hexdigest() != expected_hash:
                errors.append('Sample checksum mismatch: ' + name)
    if errors:
        raise ValueError('\n'.join(errors[:30]) + ('\nFurther errors: ' + str(len(errors) - 30) if len(errors) > 30 else ''))
    return {'snapshot': 'index' if tree.indexed else 'export', 'files': len(tree.entries),
            'bytes': sum(tree.sizes.values()), 'allowlisted_artifacts': len(assets),
            'document_dependencies_checked': checked,
            'dependency_exceptions': {k: sum(x['kind'] == k for x in issues)
                                      for k in ('missing', 'external', 'template')}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--index', action='store_true', help='Validate staged blobs (default)')
    mode.add_argument('--tree', type=Path, help='Validate an isolated clean export, with no Git metadata')
    mode.add_argument('--write-ignore', action='store_true', help='Regenerate worktree .gitignore from policy and assets; does not stage')
    parser.add_argument('--audit-links', action='store_true', help='List dependency issues for review, without accepting them')
    args = parser.parse_args()
    if args.write_ignore:
        policy = json.loads((ROOT / POLICY).read_text(encoding='utf-8'))
        assets = {line for line in (ROOT / ASSETS).read_text(encoding='utf-8').splitlines()
                  if line and not line.startswith('#')}
        with (ROOT / '.gitignore').open('w', encoding='utf-8', newline='\n') as stream:
            stream.write(ignore_text(policy, assets))
        return
    tree = Snapshot(args.tree.resolve() if args.tree else ROOT, not bool(args.tree))
    if args.audit_links:
        print(json.dumps(dependencies(tree)[1], ensure_ascii=False, indent=2))
        return
    result = validate(tree)
    if tree.indexed:
        subprocess.run(['git', '-C', str(ROOT), 'diff', '--cached', '--check'], check=True)
    print(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, SyntaxError, subprocess.CalledProcessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
